"""Writes js/doll_base.js: 奕叡's own pixels as NES palette indices, the base the paper doll (js/doll.js) dresses.

- the field sprite (16x24) facing down, side (right) and up: frame 1's body plus frame 2's legs (the bottom 5 rows),
  the walk rule every sprite in the game follows
- the 48x56 dialogue portrait

Run: python -P tools/doll.py (after tools/people.py, which copies his sheet and portrait from the Character Gallery).
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NES = [
    0x7C7C7C, 0x0000FC, 0x0000BC, 0x4428BC, 0x940084, 0xA80020, 0xA81000, 0x881400, 0x503000, 0x007800, 0x006800, 0x005800, 0x004058, 0x000000, 0x000000, 0x000000,
    0xBCBCBC, 0x0078F8, 0x0058F8, 0x6844FC, 0xD800CC, 0xE40058, 0xF83800, 0xE45C10, 0xAC7C00, 0x00B800, 0x00A800, 0x00A844, 0x008888, 0x000000, 0x000000, 0x000000,
    0xF8F8F8, 0x3CBCFC, 0x6888FC, 0x9878F8, 0xF878F8, 0xF85898, 0xF87858, 0xFCA044, 0xF8B800, 0xB8F818, 0x58D854, 0x58F898, 0x00E8D8, 0x787878, 0x000000, 0x000000,
    0xFCFCFC, 0xA4E4FC, 0xB8B8F8, 0xD8B8F8, 0xF8B8F8, 0xF8A4C0, 0xF0D0B0, 0xFCE0A8, 0xF8D878, 0xD8F878, 0xB8F8B8, 0xB8F8D8, 0x00FCFC, 0xF8D8F8, 0x000000, 0x000000,
]


def index_of(rgb):
    v = (rgb[0] << 16) | (rgb[1] << 8) | rgb[2]
    if v == 0:
        return 0x0F
    for i, c in enumerate(NES):
        if c == v:
            return i
    raise ValueError('not an NES colour: #%06x' % v)


def grid(im, x0, y0, w, h, legs=None):
    rows = []
    for y in range(h):
        src = (im, x0, y0) if legs is None or y < h - 5 else legs
        row = []
        for x in range(w):
            p = src[0].getpixel((src[1] + x, src[2] + y))
            row.append(-1 if p[3] < 128 else index_of(p[:3]))
        rows.append(row)
    return rows


def enc(rows):
    # one character per pixel: '.' transparent, else a key into the palette list written next to it
    pal = sorted({v for r in rows for v in r if v >= 0})
    keys = '0123456789abcdefghijklmnopqrstuvwxyz'
    lines = [''.join('.' if v < 0 else keys[pal.index(v)] for v in r) for r in rows]
    return pal, lines


def main():
    sheet = Image.open(os.path.join(ROOT, 'assets', 'people', 'yirui_sheet.png')).convert('RGBA')
    npcs = Image.open(os.path.join(ROOT, 'assets', 'people', 'npcs.png')).convert('RGBA')
    por = Image.open(os.path.join(ROOT, 'assets', 'people', 'yirui_portrait.png')).convert('RGBA')
    # rects as in js/people_art.js: the walk rows of his sheet, and hero_back in npcs.png
    views = {
        'down': grid(sheet, 0, 24, 16, 24, legs=(sheet, 16, 24)),
        'side': grid(sheet, 0, 48, 16, 24, legs=(sheet, 16, 48)),
        'up': grid(npcs, 136, 25, 16, 24, legs=(npcs, 153, 25)),
        'down0': grid(sheet, 0, 24, 16, 24),
        'side0': grid(sheet, 0, 48, 16, 24),
        'up0': grid(npcs, 136, 25, 16, 24),
    }
    out = ['// generated by tools/doll.py - 奕叡\'s own pixels (NES palette indices) for the paper doll in doll.js.',
           '// SPRITE[view] = [frame 1, frame 2]: frame 2 has the same body, only the bottom 5 rows (the legs) step.',
           '// Each grid: { pal: [NES index per key], rows: [...] }, \'.\' = transparent.',
           'export const SPRITE = {']
    for v in ('down', 'side', 'up'):
        out.append('  %s: [' % v)
        for g in (views[v + '0'], views[v]):
            pal, lines = enc(g)
            out.append('    { pal: [%s], rows: [' % ', '.join('0x%02X' % p for p in pal))
            out += ["      '%s'," % l for l in lines]
            out.append('    ] },')
        out.append('  ],')
    out.append('};')
    pal, lines = enc(grid(por, 0, 0, 48, 56))
    out.append('export const PORTRAIT = { pal: [%s], rows: [' % ', '.join('0x%02X' % p for p in pal))
    out += ["  '%s'," % l for l in lines]
    out.append('] };')
    with open(os.path.join(ROOT, 'js', 'doll_base.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote js/doll_base.js')


if __name__ == '__main__':
    main()
