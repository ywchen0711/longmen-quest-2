"""Enemy art for 龍門刀客傳 Longmen Quest, taken from the Character Gallery.

    python -P tools/gallery.py              (from C:\\LongmenQuest)
    python -P tools/gallery.py --sheet PATH also writes a 4x contact sheet

Reads C:\\CharacterGallery\\chars\\index.json and copies, for the 50 common foes (faction 'foe', tiers 1-5) and the
9 big beasts (faction 'beast'), the battle picture (nes/portrait.png, transparent) and the two 16x16 (or 16x24)
field frames (nes/sheet.png, row 0) into one atlas, assets/enemies.png (1x pixels, 1px gap). The Golden Arhat, the
one creature the gallery does not have, is still drawn by tools/enemies.py.

Writes js/enemy_art.js:
  ENEMY_ART   per enemy id: the battle picture rect { x, y, w, h } and, when it has one, the field frames
              f: [x, y, w, h] (frame 2 sits w pixels to the right of frame 1).
  ENEMY_INFO  per enemy id: tier, bilingual name, bio and habitat from the gallery (used by the bestiary).
Enemy ids are 'e_' + gallery id for the common foes and 'bx_' + gallery id for the beasts.
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import enemies as legacy  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GALLERY = r'C:\CharacterGallery'


def load():
    idx = json.load(open(os.path.join(GALLERY, 'chars', 'index.json'), encoding='utf-8'))
    out = []
    for c in idx['characters']:
        if c.get('faction') not in ('foe', 'beast'):
            continue
        v = next(v for v in c['variants'] if v['style'] == 'nes')
        eid = ('e_' if c['faction'] == 'foe' else 'bx_') + c['id']
        por = Image.open(os.path.join(GALLERY, v['files']['portrait'])).convert('RGBA')
        sheet = Image.open(os.path.join(GALLERY, v['files']['sheet'])).convert('RGBA')
        meta = json.load(open(os.path.join(GALLERY, v['files']['sheetJson']), encoding='utf-8'))
        fw, fh = meta['frameWidth'], meta['frameHeight']
        row = meta['animations']['move']['row']
        field = sheet.crop((0, row * fh, 2 * fw, (row + 1) * fh))
        info = {'tier': c.get('tier', 0), 'zh': c['name']['zh'], 'en': c['name']['en'],
                'bio': c['bio'], 'habitat': c.get('habitat', {'zh': '', 'en': ''})}
        out.append((eid, por, field, fw, info))
    return out


def build():
    items = load()
    # the Golden Arhat keeps its hand-typed picture
    arhat = next(e for e in legacy.ENEMIES if e[0] == 'b_luohan')
    items.append(('b_luohan', legacy.make(arhat[0], arhat[1], arhat[2]).image(), None, 0, None))
    W = 512
    x = y = rowh = 0
    place = []
    for eid, por, field, fw, info in items:
        parts = [por] + ([field] if field else [])
        for k, im in enumerate(parts):
            if x + im.width > W:
                x, y, rowh = 0, y + rowh + 1, 0
            place.append((eid, k, x, y, im))
            x += im.width + 1
            rowh = max(rowh, im.height)
    sheet = Image.new('RGBA', (W, y + rowh), (0, 0, 0, 0))
    rects = {}
    for eid, k, px, py, im in place:
        sheet.alpha_composite(im, (px, py))
        r = rects.setdefault(eid, {})
        if k == 0:
            r.update(x=px, y=py, w=im.width, h=im.height)
        else:
            r['f'] = [px, py, im.width // 2, im.height]
    return items, sheet, rects


def contact(items, path, scale=4, cols=10):
    from PIL import ImageDraw
    cw, ch = 64 * scale + 16, 56 * scale + 40
    rows = (len(items) + cols - 1) // cols
    out = Image.new('RGB', (cols * cw, rows * ch), (0, 0, 0))
    d = ImageDraw.Draw(out)
    for i, (eid, por, field, fw, info) in enumerate(items):
        cx, cy = (i % cols) * cw, (i // cols) * ch
        big = por.resize((por.width * scale, por.height * scale), Image.NEAREST)
        out.paste(big, (cx + (cw - big.width) // 2, cy + 4 + 56 * scale - big.height), big)
        d.text((cx + 4, cy + 56 * scale + 10), eid, fill=(255, 255, 255))
    out.save(path)


def main():
    items, sheet, rects = build()
    sheet.save(os.path.join(ROOT, 'assets', 'enemies.png'))
    lines = ['// generated by tools/gallery.py from the Character Gallery - rects into assets/enemies.png (1x pixels).',
             '// f = the two field frames (frame 2 is w pixels right of frame 1).',
             'export const ENEMY_ART = {']
    for eid, *_ in items:
        r = rects[eid]
        f = (', f: [%d, %d, %d, %d]' % tuple(r['f'])) if 'f' in r else ''
        lines.append('  %s: { x: %d, y: %d, w: %d, h: %d%s },' % (eid, r['x'], r['y'], r['w'], r['h'], f))
    lines.append('};')
    lines.append('// names, bios and habitats from C:\\CharacterGallery\\chars\\index.json (shown in the bestiary)')
    lines.append('export const ENEMY_INFO = {')
    for eid, por, field, fw, info in items:
        if info:
            lines.append('  %s: %s,' % (eid, json.dumps(info, ensure_ascii=False)))
    lines.append('};')
    with open(os.path.join(ROOT, 'js', 'enemy_art.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    if '--sheet' in sys.argv:
        contact(items, sys.argv[sys.argv.index('--sheet') + 1])
    print('%d enemies, atlas %dx%d' % (len(items), sheet.width, sheet.height))


if __name__ == '__main__':
    main()
